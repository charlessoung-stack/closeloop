import { useState } from "react";
import { AgentSuggestion, ScoreBadge, StageBadge, type Closeloop, type Lead, type QualificationResult } from "@closeloop/core";
import { LeadForm } from "./LeadForm";
import { QualifyChat } from "./QualifyChat";

export function LandingPage({
  closeloop,
  onDataChanged,
}: {
  closeloop: Closeloop;
  onDataChanged: () => void;
}) {
  const [current, setCurrent] = useState<Lead | null>(null);
  const [verdict, setVerdict] = useState<QualificationResult | null>(null);

  const handleCreated = (lead: Lead, result: QualificationResult) => {
    setCurrent(lead);
    setVerdict(result);
    onDataChanged();
  };

  const handleUpdated = (lead: Lead) => {
    setCurrent(lead);
    setVerdict(lead.qualification ?? null);
    onDataChanged();
  };

  return (
    <div className="landing">
      <section className="hero">
        <h1>Stop losing inbound leads.</h1>
        <p>
          Closeloop's LeadGen agent captures every inquiry, qualifies it in seconds with
          scored, explainable reasons, and hands the warm ones to your pipeline.
        </p>
        <div className="hero-steps">
          <span>1 · Capture</span>
          <span>2 · Qualify</span>
          <span>3 · Route</span>
          <span>4 · Track</span>
        </div>
      </section>

      <div className="landing-grid">
        <div>
          <h2 className="section-title">New inbound lead</h2>
          <LeadForm closeloop={closeloop} onCreated={handleCreated} />
        </div>

        <aside className="right-rail">
          <h2 className="section-title">Agent workspace</h2>
          {current ? (
            <>
              <QualifyChat lead={current} closeloop={closeloop} onUpdated={handleUpdated} />
              <div className="verdict">
                <header>
                  <strong>{current.company}</strong>
                  <ScoreBadge score={current.score} />
                  <StageBadge stage={current.stage} />
                </header>
                {verdict && (
                  <>
                    <ul className="reasons">
                      {verdict.reasons.map((r, i) => (
                        <li key={i}>{r}</li>
                      ))}
                    </ul>
                    <AgentSuggestion
                      suggestion={{
                        action: verdict.nextAction,
                        priority: verdict.score >= 70 ? "high" : verdict.score >= 40 ? "mid" : "low",
                        dueInDays: verdict.score >= 70 ? 1 : verdict.score >= 40 ? 2 : 7,
                        reason: "Generated by the qualification agent from the signals above.",
                      }}
                    />
                  </>
                )}
              </div>
            </>
          ) : (
            <p className="muted">Submit a lead to see the qualification agent in action.</p>
          )}
        </aside>
      </div>
    </div>
  );
}
